#!/usr/bin/env python
"""Build an NPU-stack constraints file from a `pip freeze` dump.

We deliberately do NOT use the whole freeze as constraints. The verified container has
packages (librosa, matplotlib, ...) whose declared deps require ``numpy>=2`` while the
Ascend stack pins ``numpy==1.26.4``; pinning them all makes pip's resolver fail with
"ResolutionImpossible". Only the NPU-critical stack must never drift, so we keep an
allowlist and let everything else resolve to versions compatible with numpy 1.26.4.

Usage:
    docker exec -i <container> pip freeze > constraints-tested.txt.raw
    python scripts/clean_constraints.py constraints-tested.txt.raw deploy/constraints-npu.txt
"""
import re
import sys

# Packages that must stay identical to the verified base image.
KEEP_NAMES = {
    'torch',
    'torchvision',
    'torchaudio',
    'torch-npu',
    'triton',
    'triton-ascend',
    'numpy',
    'vllm',
    'vllm-ascend',
    'flash-linear-attention',
    'fla-core',
    'mooncake-transfer-engine-npu',
}


def canon(name: str) -> str:
    return re.sub(r'[-_.]+', '-', name).lower()


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src, dst = sys.argv[1], sys.argv[2]

    keep = []
    seen = set()
    for line in open(src, encoding='utf-8').read().splitlines():
        s = line.strip()
        if not s or s.startswith('-e') or s.startswith('#') or ' @ ' in s or '://' in s:
            continue
        if not re.match(r'^[A-Za-z0-9][A-Za-z0-9._+-]*(\[[^]]*\])?==\S', s):
            continue
        name, ver = re.split(r'==', s, 1)
        name = re.sub(r'\[[^]]*\]', '', name).strip()
        key = canon(name)
        if key not in KEEP_NAMES or key in seen:
            continue
        seen.add(key)
        keep.append(f'{name}=={ver}')

    header = ('# NPU-stack constraints (allowlist). Generated by scripts/clean_constraints.py\n'
              '# from a verified container freeze; do not add non-stack packages here.\n')
    open(dst, 'w', encoding='utf-8', newline='\n').write(header + '\n'.join(keep) + '\n')
    print(f'kept {len(keep)} lines -> {dst}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
